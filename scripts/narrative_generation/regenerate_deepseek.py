#!/usr/bin/env python
"""
Regenerate DeepSeek's include_pa and exclude_pa narratives.

Why: the original DeepSeek narratives (Aug 2026) were generated by
DeepSeek-V4-Flash-0731. Since 10 Sep 2026 the API name "deepseek-v4-flash"
is routed to DeepSeek-V4.1-Flash, which also generated the counterfactual
narratives. Regenerating both factual conditions puts all three conditions
on the same model.

What it does:
  1. Regenerates every DeepSeek include_pa / exclude_pa narrative (all
     datasets, all instances) whose timestamp is before CUTOFF (i.e. made by
     the old model), or that failed or is empty/truncated. The old files are
     overwritten.
  2. Is safe to rerun: already regenerated narratives are skipped.

Run from the repo root (NOT on eduroam -- it blocks DeepSeek):
    python scripts/narrative_generation/regenerate_deepseek_factual.py
"""

import json
import statistics
import sys
from pathlib import Path

from generate_narratives import generate_narrative, save_result

PROVIDER, MODEL = "deepseek", "deepseek-v4-flash"
DATASETS = ["credit", "saudi", "student", "law"]
CONDITIONS = ["include_pa", "exclude_pa"]
CUTOFF = "2026-09-10"  # V4.1-Flash release; older timestamps = old model
NARR = Path("results/narratives")


def needs_regeneration(path):
    try:
        d = json.load(open(path, encoding="utf-8"))
    except Exception:
        return True
    text = (d.get("narrative") or "").strip()
    return (d.get("status") != "success" or len(text) < 200
            or d.get("timestamp", "") < CUTOFF)


def main():
    if not NARR.exists():
        sys.exit("Run this from the repo root (results/narratives not found).")

    todo, word_counts = [], []
    for ds in DATASETS:
        for cond in CONDITIONS:
            folder = NARR / ds / cond / PROVIDER / MODEL
            for f in sorted(folder.glob("instance_*.json")):
                if needs_regeneration(f):
                    todo.append((ds, cond, int(f.stem.split("_")[1])))

    print(f"\n{len(todo)} narratives to regenerate\n")
    for n, (ds, cond, i) in enumerate(todo, 1):
        r = generate_narrative(ds, i, provider=PROVIDER, model=MODEL,
                               exclude_protected_attributes=(cond == "exclude_pa"))
        if r["status"] == "success" and len((r["narrative"] or "").strip()) >= 200:
            save_result(r, str(NARR))
            words = len(r["narrative"].split())
            word_counts.append(words)
            print(f"[{n}/{len(todo)}] {ds} {cond} #{i}: OK, {words} words")
        else:
            # never overwrite the old narrative with a failed one
            print(f"[{n}/{len(todo)}] {ds} {cond} #{i}: FAILED "
                  f"({r.get('error') or 'empty/short narrative'}) - kept old file, rerun later")

    if word_counts:
        print(f"\nMean length of new narratives: {statistics.mean(word_counts):.0f} words "
              f"(expected ~210 for V4.1-Flash; ~260 would mean the old model)")
    print("Rerun until it reports 0 narratives to regenerate.")


if __name__ == "__main__":
    main()